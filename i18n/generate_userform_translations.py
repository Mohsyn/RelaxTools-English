def main():
    print(f"Total phrases to register: {len(TRANSLATIONS)}")

    # 1. Update translation_cache.json
    cache = json.loads(CACHE_FILE.read_text(encoding="utf-8")) if CACHE_FILE.exists() else {}
    updated = 0
    for ja, en in TRANSLATIONS.items():
        cache[ja] = en
        # Also newline variants
        cache[ja.replace("\r\n", "\n")] = en
        updated += 1

    CACHE_FILE.write_text(json.dumps(cache, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Updated {CACHE_FILE} with {updated} phrases. Total cache entries: {len(cache)}")

    # 2. Append new approved translations to strings_raw.csv if not already present
    existing_raw = set()
    rows = []
    if CSV_FILE.exists():
        with open(CSV_FILE, "r", encoding="utf-8-sig", newline="") as f:
            reader = csv.DictReader(f)
            fieldnames = reader.fieldnames or ["file", "line", "context", "attr_name", "ja_text", "en_text", "status"]
            for r in reader:
                existing_raw.add(r.get("ja_text", "").strip())
                rows.append(r)
    else:
        fieldnames = ["file", "line", "context", "attr_name", "ja_text", "en_text", "status"]

    added_to_csv = 0
    for ja, en in TRANSLATIONS.items():
        if ja not in existing_raw:
            rows.append({
                "file": "Source/src/Form/*.frm",
                "line": "1",
                "context": "property",
                "attr_name": "Caption",
                "ja_text": ja,
                "en_text": en,
                "status": "approved"
            })
            existing_raw.add(ja)
            added_to_csv += 1

    with open(CSV_FILE, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Appended {added_to_csv} new approved phrases to {CSV_FILE}. Total rows: {len(rows)}")

if __name__ == "__main__":
    main()
